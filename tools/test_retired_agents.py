    def test_symlink_and_parent_symlink_blocked(self):
        self.path.unlink()
        other = self.home / "other.md"
        other.write_bytes(self.bytes)
        self.path.symlink_to(other)
        self.assertEqual(self.run_migration(), 1)
        self.assertTrue(other.exists())
        self.path.unlink()
        self.dest.rmdir()
        self.dest.symlink_to(self.home)
        self.assertEqual(self.run_migration(), 1)

    def test_nonregular_candidate_rejected_before_open(self):
        self.path.unlink()
        self.path.mkdir()
        with patch.object(migration.os, "open", side_effect=OSError("must not open directory")) as opened:
            with self.assertRaises(OSError):
                migration.read_regular(self.path)
            opened.assert_not_called()

    def test_copy_failure_and_changed_original_preserved(self):
        with patch.object(migration, "write_backup", side_effect=OSError("copy failed")):
            self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.path.read_bytes(), self.bytes)
        original = migration.write_backup
        def changed(*args):
            result = original(*args)
            self.path.write_bytes(b"changed during backup")
            return result
        with patch.object(migration, "write_backup", side_effect=changed):
            self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.path.read_bytes(), b"changed during backup")

    def test_bad_backup_and_unique_retry_preserve_evidence(self):
        original = migration.write_backup
        def corrupt(*args):
            target = original(*args)
            target.write_bytes(b"corrupt")
            return target
        with patch.object(migration, "write_backup", side_effect=corrupt):
            self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.path.read_bytes(), self.bytes)
        self.assertEqual(self.run_migration(), 0)
        copies = list(self.backup.rglob("*.md"))
        self.assertEqual(len(copies), 2)
        self.assertEqual({p.read_bytes() for p in copies}, {b"corrupt", self.bytes})

