    def test_post_unlink_failure_recovers_without_overwrite(self):
        original = migration.remove_verified
        def failed_after_unlink(*args):
            original(*args)
            raise OSError("post-unlink failure")
        with patch.object(migration, "remove_verified", side_effect=failed_after_unlink):
            self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.path.read_bytes(), self.bytes)
        def recreated(*args):
            original(*args)
            self.path.write_bytes(b"new user work")
            raise OSError("post-unlink failure")
        with patch.object(migration, "remove_verified", side_effect=recreated):
            self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.path.read_bytes(), b"new user work")

