    def test_real_wrappers_opt_in_force_dry_run_and_invalid_flags(self):
        for platform in test_install.PLATFORMS:
            with self.subTest(platform=platform), tempfile.TemporaryDirectory() as temporary:
                base = Path(temporary).resolve()
                repo = test_install.build_repo(base)
                manifest_path = repo / "canonical/manifest.json"
                manifest = json.loads(manifest_path.read_text())
                manifest["agents"] = [a for a in manifest["agents"] if a not in migration.IDS]
                # Keep this fixture focused on one stable skill, independently of
                # the main renderer's current documentation resources.
                manifest["skills"] = ["git-commit"]
                manifest_path.write_text(json.dumps(manifest))
                for entry in self.catalog:
                    if entry["platform"] == platform:
                        (repo / "generated" / platform / "agents" / entry["filename"]).unlink(missing_ok=True)
                home = base / "home"
                home.mkdir()
                _, dest = test_install.installed_paths(home, platform)
                dest.mkdir(parents=True)
                entry = next(e for e in self.catalog if e["platform"] == platform and e["id"] == "architecture")
                path = dest / entry["filename"]
                old = subprocess.check_output(["git", "show", f'{PINNED}:generated/{platform}/agents/{entry["filename"]}'], cwd=ROOT)
                path.write_bytes(old)
                result = test_install.run_installer(repo, home, platform, "--approve-retired-file", str(path))
                self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
                self.assertEqual(list(home.rglob("*.md")), [path])
                result = test_install.run_installer(repo, home, platform, "--force")
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(path.read_bytes(), old)
                self.assertIn("migración", result.stdout)
                before = [(p, p.stat().st_mtime_ns) for p in home.rglob("*")]
                result = test_install.run_installer(repo, home, platform, "--migrate-retired-agents", "--dry-run")
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(before, [(p, p.stat().st_mtime_ns) for p in home.rglob("*")])
                result = test_install.run_installer(repo, home, platform, "--migrate-retired-agents", "--force")
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertFalse(path.exists())
                copies = list((home / ".ai-agents-kit-retired-backups").rglob("*.md"))
                self.assertEqual(len(copies), 1)
                self.assertEqual(copies[0].read_bytes(), old)
                # --force never approves unknown bytes; approvals are repeatable.
                path.write_bytes(b"custom architecture")
                other_entry = next(e for e in self.catalog if e["platform"] == platform and e["id"] == "project-navigator")
                other = dest / other_entry["filename"]
                other.write_bytes(b"custom navigator")
                extra = dest / "personal.md"
                extra.write_bytes(b"personal agent")
                result = test_install.run_installer(repo, home, platform, "--migrate-retired-agents", "--force")
                self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
                self.assertEqual(path.read_bytes(), b"custom architecture")
                self.assertEqual(other.read_bytes(), b"custom navigator")
                flags = ["--migrate-retired-agents", "--force"]
                for candidate in (path, other):
                    flags.extend(["--approve-retired-file", str(candidate), "--approve-retired-sha256", hashlib.sha256(candidate.read_bytes()).hexdigest()])
                result = test_install.run_installer(repo, home, platform, *flags)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertFalse(path.exists())
                self.assertFalse(other.exists())
                self.assertEqual(extra.read_bytes(), b"personal agent")
                copies = list((home / ".ai-agents-kit-retired-backups").rglob("*.md"))
                self.assertEqual(len(copies), 3)
                result = test_install.run_installer(repo, home, platform, "--migrate-retired-agents", "--force")
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(list((home / ".ai-agents-kit-retired-backups").rglob("*.md")), copies)

