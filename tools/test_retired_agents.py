        self.assertEqual(migration.migrate("claude", destinations, self.backup), 0)
        copies = list(self.backup.rglob("*.md"))
        self.assertEqual(len(copies), 2)
        self.assertTrue(all(p.read_bytes() == self.bytes for p in copies))
        self.assertTrue(all(not (dest / "architecture.md").exists() for dest in destinations))

