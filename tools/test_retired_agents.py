    def test_wrappers_reject_unsafe_copy_targets_before_writes(self):
        for platform in test_install.PLATFORMS:
            for defect in ("skills-root-link", "skill-link", "nested-reference-link", "reference-file-link", "current-agent-link", "backup-file", "backup-parent-file"):
                with self.subTest(platform=platform, defect=defect), tempfile.TemporaryDirectory() as temporary:
                    base = Path(temporary).resolve()
                    repo = test_install.build_repo(base)
                    home = base / "home"
                    home.mkdir()
                    skills, agents = test_install.installed_paths(home, platform)
                    agents.mkdir(parents=True)
                    entry = next(e for e in self.catalog if e["platform"] == platform and e["id"] == "architecture")
                    candidate = agents / entry["filename"]
                    candidate.write_bytes(b"original retired custom")
                    outside = base / "outside"
                    outside.mkdir()
                    sentinel = outside / "sentinel.md"
                    sentinel.write_bytes(b"outside must not change")
                    if defect == "skills-root-link":
                        skills.symlink_to(outside, target_is_directory=True)
                    elif defect == "skill-link":
                        skills.mkdir()
                        (skills / "architecture").symlink_to(outside, target_is_directory=True)
                    elif defect in {"nested-reference-link", "reference-file-link"}:
                        skill = skills / "architecture"
                        skill.mkdir(parents=True)
                        if defect == "nested-reference-link":
                            (skill / "references").symlink_to(outside, target_is_directory=True)
                        else:
                            (skill / "references").mkdir()
                            (skill / "references/templates.md").symlink_to(sentinel)
                    elif defect == "current-agent-link":
                        name = test_install.agent_filenames(platform, ["documentation-orchestrator"])[0]
                        (agents / name).symlink_to(sentinel)
                    else:
                        backup = home / ".ai-agents-kit-retired-backups"
                        backup.write_bytes(b"not a directory")
                        if defect == "backup-parent-file":
                            # Exercise an existing non-directory parent as well.
                            backup.unlink()
                            backup.mkdir()
                            (backup / "blocked").write_bytes(b"not a directory")
                            script = repo / f"scripts/install/{platform}.sh"
                            script.write_text(script.read_text().replace('$HOME/.ai-agents-kit-retired-backups', '$HOME/.ai-agents-kit-retired-backups/blocked/child'))
                    before_home = [(str(p), p.lstat().st_mtime_ns) for p in home.rglob("*")]
                    before_outside = [(str(p), hashlib.sha256(p.read_bytes()).hexdigest()) for p in outside.rglob("*") if p.is_file()]
                    result = test_install.run_installer(repo, home, platform, "--migrate-retired-agents", "--force")
                    self.assertEqual([(str(p), hashlib.sha256(p.read_bytes()).hexdigest()) for p in outside.rglob("*") if p.is_file()], before_outside, result.stdout + result.stderr)
                    self.assertEqual([(str(p), p.lstat().st_mtime_ns) for p in home.rglob("*")], before_home, result.stdout + result.stderr)
                    self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
                    self.assertEqual(candidate.read_bytes(), b"original retired custom")

