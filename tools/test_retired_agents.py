"""Focused migration tests; all destinations and HOME are temporary.

Requires Git history containing PINNED, including its generated artifacts and
adapters. CI must checkout with fetch-depth: 0 (or fetch that commit explicitly).
Missing historical evidence fails the suite; never silently skip these checks or
substitute current generated bytes for the pinned baseline.
"""
import copy
import contextlib
import hashlib
import io
import json
import os
import re
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import retired_agents as migration
import test_install

ROOT = Path(__file__).resolve().parent.parent
PINNED = "d206ae811b14c44699c7040bdb59742eac1f122d"


class MigrationTests(unittest.TestCase):
    def setUp(self):
        output = contextlib.redirect_stdout(io.StringIO())
        output.__enter__()
        self.addCleanup(output.__exit__, None, None, None)
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.home = Path(self.temp.name).resolve()
        self.env = patch.dict(os.environ, {"HOME": str(self.home), "USERPROFILE": str(self.home)})
        self.env.start()
        self.addCleanup(self.env.stop)
        self.dest = self.home / ".claude/agents"
        self.dest.mkdir(parents=True)
        self.catalog = migration.load_catalog()
        self.entry = next(e for e in self.catalog if e["platform"] == "claude" and e["id"] == "architecture")
        self.path = self.dest / self.entry["filename"]
        self.bytes = subprocess.check_output(["git", "show", f"{PINNED}:generated/claude/agents/architecture.md"], cwd=ROOT)
        self.path.write_bytes(self.bytes)
        self.backup = self.home / "kit-retired-backups"

    def run_migration(self, **kwargs):
        return migration.migrate("claude", [self.dest], self.backup, **kwargs)

    def test_catalog_pinned_git_evidence(self):
        data = json.loads((ROOT / "tools/retired_agents.json").read_text())
        self.assertEqual(data["baseline_commit"], PINNED)
        self.assertEqual(len(self.catalog), 12)
        for entry in self.catalog:
            adapter = subprocess.check_output(["git", "show", f'{PINNED}:adapters/{entry["platform"]}/agents/{entry["id"]}.json'], cwd=ROOT)
            self.assertEqual(hashlib.sha256(adapter).hexdigest(), entry["adapter_sha256"])
            self.assertEqual(json.loads(adapter)["filename"], entry["filename"])
            artifact = subprocess.check_output(["git", "show", f'{PINNED}:generated/{entry["platform"]}/agents/{entry["filename"]}'], cwd=ROOT)
            self.assertEqual(hashlib.sha256(artifact).hexdigest(), entry["sha256"])

    def test_catalog_rejects_invalid_entries(self):
        data = json.loads((ROOT / "tools/retired_agents.json").read_text())
        for key, value in (("filename", "../architecture.md"), ("platform", "unknown"), ("id", "sdd"), ("sha256", "bad")):
            invalid = copy.deepcopy(data)
            invalid["entries"][0][key] = value
            with self.assertRaises(ValueError):
                migration.validate_catalog(invalid)
        invalid = copy.deepcopy(data)
        invalid["entries"].pop()
        with self.assertRaises(ValueError):
            migration.validate_catalog(invalid)

    def test_known_backup_restore_and_idempotence(self):
        self.assertEqual(self.run_migration(), 0)
        self.assertFalse(self.path.exists())
        copies = list(self.backup.rglob("*.md"))
        self.assertEqual(len(copies), 1)
        self.assertEqual(copies[0].read_bytes(), self.bytes)
        self.assertEqual(self.run_migration(), 0)
        self.assertEqual(list(self.backup.rglob("*.md")), copies)
        migration.restore(copies[0], self.path, self.entry["sha256"])
        with self.assertRaises(FileExistsError):
            migration.restore(copies[0], self.path, self.entry["sha256"])

    def test_uncertain_requires_exact_path_and_matching_hash(self):
        self.path.write_bytes(b"custom")
        sha = hashlib.sha256(b"custom").hexdigest()
        self.assertEqual(self.run_migration(), 1)
        self.assertEqual(self.run_migration(dry_run=True), 1)
        self.assertEqual(self.run_migration(approvals={str(self.path): "0" * 64}), 1)
        self.assertEqual(self.path.read_bytes(), b"custom")
        self.assertEqual(self.run_migration(approvals={str(self.path): sha}), 0)
        self.assertEqual(next(self.backup.rglob("*.md")).read_bytes(), b"custom")

    def test_dry_run_zero_writes(self):
        before = [(p, p.stat().st_mtime_ns) for p in self.home.rglob("*")]
